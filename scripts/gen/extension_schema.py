def gofmt(src: str) -> str:
    exe = shutil.which("gofmt")
    if not exe:
        raise SchemaError("gofmt is not on PATH: the Go output is gofmt's")
    r = subprocess.run([exe], input=src, capture_output=True, text=True)
    if r.returncode != 0:
        raise SchemaError("gofmt: " + r.stderr.strip())
    return r.stdout


def outputs(defs: dict[str, Def]) -> dict[Path, str]:
    ts = gen_ts(defs)
    out = {GO_OUT: gofmt(gen_go(defs)), SWIFT_OUT: gen_swift(defs), KOTLIN_OUT: gen_kotlin(defs)}
    for p in TS_OUTS:
        out[p] = ts
    return {p: (s.rstrip("\n") + "\n") for p, s in out.items()}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on a difference")
    args = ap.parse_args()
    try:
        files = outputs(load())
    except SchemaError as e:
        print(f"schema/extension: {e}", file=sys.stderr)
        return 2
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("generated files differ from schema/extension (run python3 scripts/gen/extension_schema.py):",
              file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

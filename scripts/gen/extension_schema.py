#!/usr/bin/env python3
"""Generate the extension wire types of every language from schema/extension/ (#1849).

    python3 scripts/gen/extension_schema.py           write the generated files
    python3 scripts/gen/extension_schema.py --check   exit 1 when a generated file differs from the schema's

The schemas are the one truth of the extension manifest, the process protocol and views; this turns them into Go
(sdk/go/wire), TypeScript (sdk/ts/src/wire.ts and the web's copy), Swift (apple/Shared/Generated) and Kotlin
(android/core/contracts). Only the subset described in schema/extension/README.md is understood; anything else stops
the generator rather than being guessed at. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = ROOT / "schema" / "extension"
SCHEMA_FILES = ["manifest.schema.json", "protocol.schema.json", "view.schema.json"]

GO_OUT = ROOT / "sdk/go/wire/wire_gen.go"
TS_OUTS = [ROOT / "sdk/ts/src/wire.ts", ROOT / "web/src/lib/extension-wire.ts"]
SWIFT_OUT = ROOT / "apple/Shared/Generated/ExtensionWire.swift"
KOTLIN_OUT = ROOT / "android/core/contracts/src/main/kotlin/persona/core/contracts/generated/ExtensionWire.kt"

HEADER = "Generated by scripts/gen/extension_schema.py from schema/extension/; do not edit."


class SchemaError(Exception):
    pass


# ---------------------------------------------------------------------------------------------------------------------
# Loading the schemas into a small model: definitions that are structs, string enums, unions told apart by a field, or
# free JSON; fields with a type made of primitives, arrays, maps and references.


@dataclass
class TypeRef:
    kind: str  # string | int | int64 | number | bool | time | any | array | map | ref
    of: "TypeRef | None" = None
    ref: str = ""


@dataclass
class Field:
    name: str
    type: TypeRef
    required: bool
    doc: str = ""
    pointer: bool = False  # x-go-pointer: a Go number whose absence means something


@dataclass
class Def:
    name: str
    kind: str  # struct | enum | union | any
    doc: str = ""
    fields: list[Field] = field(default_factory=list)
    values: list[str] = field(default_factory=list)  # enum
    variants: list[str] = field(default_factory=list)  # union: the variants' defs
    discriminator: str = ""
    tag: str = ""  # a union variant's discriminator value
    since: int = 0  # x-since of a union variant
    union: str = ""  # the union a variant belongs to


def is_scalar(s: dict) -> bool:
    return s.get("type") in ("string", "integer", "number", "boolean") and "enum" not in s


def load() -> dict[str, Def]:
    raw: dict[str, tuple[str, dict]] = {}
    for f in SCHEMA_FILES:
        doc = json.loads((SCHEMA_DIR / f).read_text())
        for name, s in doc.get("$defs", {}).items():
            if name in raw:
                raise SchemaError(f"{f}: $defs/{name} is also in {raw[name][0]}: definition names are global")
            raw[name] = (f, s)

    def resolve(ref: str, here: str) -> str:
        m = re.fullmatch(r"(?:([a-z.]+\.json))?#/\$defs/([A-Za-z0-9]+)", ref)
        if not m:
            raise SchemaError(f"{here}: $ref {ref!r}: only #/$defs/X and <file>.json#/$defs/X")
        f, name = m.group(1) or raw.get(here, (None,))[0], m.group(2)
        if name not in raw:
            raise SchemaError(f"$ref {ref!r}: no definition {name}")
        if m.group(1) and raw[name][0] != m.group(1):
            raise SchemaError(f"$ref {ref!r}: {name} is in {raw[name][0]}")
        return name

    def typeof(s: dict, at: str) -> TypeRef:
        if "$ref" in s:
            name = resolve(s["$ref"], at.split(".")[0])
            target = raw[name][1]
            if target.get("x-untagged"):
                return TypeRef("any")
            if is_scalar(target):
                return typeof(target, name)
            return TypeRef("ref", ref=name)
        t = s.get("type")
        if t is None:
            if "const" in s:
                return TypeRef("string")
            return TypeRef("any")
        if t == "string":
            return TypeRef("time") if s.get("format") == "date-time" else TypeRef("string")
        if t == "integer":
            return TypeRef("int64") if s.get("x-go-type") == "int64" else TypeRef("int")
        if t == "number":
            return TypeRef("number")
        if t == "boolean":
            return TypeRef("bool")
        if t == "array":
            return TypeRef("array", of=typeof(s.get("items", {}), at))
        if t == "object":
            if s.get("properties"):
                raise SchemaError(f"{at}: an inline object with properties: make it a definition")
            ap = s.get("additionalProperties", {})
            return TypeRef("map", of=typeof(ap if isinstance(ap, dict) else {}, at))
        raise SchemaError(f"{at}: type {t!r} is not in the subset")

    defs: dict[str, Def] = {}
    for name, (f, s) in raw.items():
        doc = s.get("description", "")
        if is_scalar(s):
            continue  # a named string (an id, a host): used as its type where it is referenced
        if s.get("x-untagged"):
            defs[name] = Def(name, "any", doc)
        elif "oneOf" in s:
            disc = s.get("x-discriminator")
            if not disc:
                raise SchemaError(f"{name}: a oneOf needs x-discriminator (or x-untagged for free JSON)")
            variants = [resolve(v["$ref"], name) for v in s["oneOf"]]
            defs[name] = Def(name, "union", doc, variants=variants, discriminator=disc)
        elif s.get("type") == "string" and "enum" in s:
            defs[name] = Def(name, "enum", doc, values=list(s["enum"]))
        elif s.get("type") == "object":
            fields = []
            req = set(s.get("required", []))
            for fname, fs in s.get("properties", {}).items():
                fields.append(Field(fname, typeof(fs, f"{name}.{fname}"), fname in req, fs.get("description", ""),
                                    bool(fs.get("x-go-pointer"))))
            defs[name] = Def(name, "struct", doc, fields=fields, since=s.get("x-since", 0))
        else:
            raise SchemaError(f"{name}: not a struct, string enum, discriminated union or x-untagged")

    for u in [d for d in defs.values() if d.kind == "union"]:
        for v in u.variants:
            vd = defs[v]
            if vd.kind != "struct":
                raise SchemaError(f"{u.name}: variant {v} is not an object")
            tagf = next((x for x in vd.fields if x.name == u.discriminator), None)
            const = raw[v][1]["properties"].get(u.discriminator, {}).get("const")
            if tagf is None or not tagf.required or not isinstance(const, str):
                raise SchemaError(f"{v}: the discriminator {u.discriminator} is required and a const string")
            if vd.union:
                raise SchemaError(f"{v}: in two unions")
            vd.tag, vd.union = const, u.name
            vd.fields = [x for x in vd.fields if x.name != u.discriminator]
        tags = [defs[v].tag for v in u.variants]
        if len(set(tags)) != len(tags):
            raise SchemaError(f"{u.name}: two variants with the same {u.discriminator}")
    return defs


def flat_fields(defs: dict[str, Def], u: Def) -> list[Field]:
    """A union's variants' fields, once each, in order of first appearance: what Go's flat struct holds."""
    out: dict[str, Field] = {}
    for v in u.variants:
        for f in defs[v].fields:
            if f.name in out:
                if not same_type(flat(defs, out[f.name].type), flat(defs, f.type)) or out[f.name].pointer != f.pointer:
                    raise SchemaError(f"{u.name}: field {f.name} has different types in its variants")
                continue
            out[f.name] = f
    return list(out.values())


def flat(defs: dict[str, Def], t: TypeRef) -> TypeRef:
    """t as Go's flat struct holds it: an enum is a string."""
    return TypeRef("string") if t.kind == "ref" and defs[t.ref].kind == "enum" else t


def same_type(a: TypeRef, b: TypeRef) -> bool:
    if a.kind != b.kind or a.ref != b.ref:
        return False
    return a.of is None and b.of is None or (a.of is not None and b.of is not None and same_type(a.of, b.of))


# ---------------------------------------------------------------------------------------------------------------------
# Names.

INITIALISMS = {"id": "ID", "url": "URL", "api": "API", "http": "HTTP", "rpc": "RPC", "ui": "UI", "tz": "TZ",
               "os": "OS", "cli": "CLI", "json": "JSON"}


def camel(s: str) -> str:
    return "".join(INITIALISMS.get(p, p[:1].upper() + p[1:]) for p in re.split(r"[_.\-]", s) if p)


def go_field(s: str) -> str:
    return "".join(INITIALISMS.get(p, p[:1].upper() + p[1:]) for p in s.split("_"))


def lower_camel(s: str) -> str:
    parts = re.split(r"[_.\-]", s)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def plural(s: str) -> str:
    if s.endswith("y") and not s.endswith("ey"):
        return s[:-1] + "ies"
    if s.endswith("s"):
        return s + "es"
    return s + "s"


def upper_snake(s: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return re.sub(r"[^A-Za-z0-9]+", "_", s).upper()


def named(name: str, doc: str) -> str:
    """A Go doc comment starting with the name: "View: a view…"."""
    if not doc:
        return ""
    if len(doc) > 1 and doc[0].isupper() and doc[1].islower():
        doc = doc[0].lower() + doc[1:]
    return f"{name}: {doc}"


def comment(prefix: str, text: str, width: int = 118) -> list[str]:
    if not text:
        return []
    words, lines, cur = text.split(), [], ""
    for w in words:
        if cur and len(prefix) + len(cur) + 1 + len(w) > width:
            lines.append(prefix + cur)
            cur = w
        else:
            cur = f"{cur} {w}" if cur else w
    if cur:
        lines.append(prefix + cur)
    return lines


# ---------------------------------------------------------------------------------------------------------------------
# Go: one package, no dependencies. A union is one flat struct (its variants' fields, all optional) with the
# discriminator: what the hub has always decoded views into.


def gen_go(defs: dict[str, Def]) -> str:
    uses_time = any(f.type.kind == "time" for d in defs.values() for f in d.fields)
    out = ["// Code generated by scripts/gen/extension_schema.py from schema/extension/. DO NOT EDIT.", "",
           "// Package wire holds the extension protocol's and views' types (schema/extension/).",
           "package wire", "", "import (", '\t"encoding/json"']
    if uses_time:
        out.append('\t"time"')
    out += [")", ""]

    def gtype(t: TypeRef, optional: bool, pointer: bool) -> str:
        k = t.kind
        if k == "string":
            return "string"
        if k == "int":
            return "*int" if pointer else "int"
        if k == "int64":
            return "int64"
        if k == "number":
            return "*float64" if pointer else "float64"
        if k == "bool":
            return "bool"
        if k == "time":
            return "time.Time"
        if k == "any":
            return "json.RawMessage"
        if k == "array":
            return "[]" + gtype(t.of, False, False)
        if k == "map":
            return "map[string]" + gtype(t.of, False, False)
        d = defs[t.ref]
        if d.kind == "enum":
            return "string"
        return ("*" if optional else "") + t.ref

    def field_line(f: Field, force_optional: bool = False) -> list[str]:
        optional = force_optional or not f.required
        typ = gtype(f.type, optional, f.pointer)
        tag = f.name
        if optional:
            tag += ",omitzero" if f.type.kind == "time" else ",omitempty"
        return comment("\t// ", f.doc) + [f"\t{go_field(f.name)} {typ} `json:\"{tag}\"`"]

    for d in defs.values():
        if d.union:
            continue
        if d.kind == "enum":
            out += comment("// ", named(d.name, d.doc) or f"Values of {d.name}.")
            out.append("const (")
            for v in d.values:
                out.append(f'\t{d.name}{camel(v)} = "{v}"')
            out += [")", "", f"// {plural(d.name)} are the values of {d.name}, in order.",
                    f"var {plural(d.name)} = []string{{{', '.join(json.dumps(v) for v in d.values)}}}", ""]
        elif d.kind == "any":
            out += comment("// ", d.doc) + [f"type {d.name} = json.RawMessage", ""]
        elif d.kind == "struct":
            out += comment("// ", named(d.name, d.doc))
            out.append(f"type {d.name} struct {{")
            for f in d.fields:
                out += field_line(f)
            out += ["}", ""]
        elif d.kind == "union":
            disc = d.discriminator
            out += comment("// ", named(d.name, d.doc) + f" One struct for every variant: {disc} says which fields "
                                  "mean something.")
            out.append(f"type {d.name} struct {{")
            out.append(f"\t{go_field(disc)} string `json:\"{disc}\"`")
            for f in flat_fields(defs, d):
                out += field_line(f, force_optional=True)
            out += ["}", "", f"// {d.name} {disc}s.", "const ("]
            for v in d.variants:
                out.append(f'\t{d.name}{camel(defs[v].tag)} = "{defs[v].tag}"')
            out += [")", "", f"// {d.name}{plural(go_field(disc))} are the {disc}s of {d.name}, in order.",
                    f"var {d.name}{plural(go_field(disc))} = []string{{"
                    + ", ".join(json.dumps(defs[v].tag) for v in d.variants) + "}", ""]
            if any(defs[v].since for v in d.variants):
                out += [f"// {d.name}Since is the UI version that brought each {disc}.",
                        f"var {d.name}Since = map[string]int{{"
                        + ", ".join(f"{json.dumps(defs[v].tag)}: {defs[v].since}" for v in d.variants) + "}", ""]
    out += ["// newDef makes a value of each definition, for tests that read examples by definition name.",
            "var newDef = map[string]func() any{"]
    for d in defs.values():
        if d.kind in ("struct", "union") and not d.union:
            out.append(f"\t{json.dumps(d.name)}: func() any {{ return new({d.name}) }},")
    out += ["}", ""]
    return "\n".join(out)


# ---------------------------------------------------------------------------------------------------------------------
# TypeScript: interfaces, a union of its variants' interfaces, string enums open to values a newer hub sends.


def gen_ts(defs: dict[str, Def]) -> str:
    out = [f"// {HEADER}", "// The extension protocol's and views' types (schema/extension/).", ""]

    def ttype(t: TypeRef) -> str:
        k = t.kind
        if k in ("string", "time"):
            return "string"
        if k in ("int", "int64", "number"):
            return "number"
        if k == "bool":
            return "boolean"
        if k == "any":
            return "unknown"
        if k == "array":
            inner = ttype(t.of)
            return f"{inner}[]" if re.fullmatch(r"\w+", inner) else f"({inner})[]"
        if k == "map":
            return f"Record<string, {ttype(t.of)}>"
        return t.ref

    def fields(fs: list[Field]) -> list[str]:
        lines = []
        for f in fs:
            if f.doc and len(f.doc) <= 108:
                lines.append(f"  /** {f.doc} */")
            elif f.doc:
                lines += ["  /**"] + comment("   * ", f.doc) + ["   */"]
            lines.append(f"  {f.name}{'' if f.required else '?'}: {ttype(f.type)};")
        return lines

    def doc(text: str) -> list[str]:
        if not text:
            return []
        return ["/**"] + comment(" * ", text) + [" */"]

    for d in defs.values():
        if d.kind == "enum":
            out += doc(d.doc)
            out.append(f"export type {d.name} = {' | '.join(json.dumps(v) for v in d.values)} | (string & {{}});")
            out.append(f"export const {upper_snake(plural(d.name))} = [{', '.join(json.dumps(v) for v in d.values)}] "
                       "as const;")
            out.append("")
        elif d.kind == "any":
            out += doc(d.doc) + [f"export type {d.name} = unknown;", ""]
        elif d.kind == "struct":
            out += doc(d.doc)
            out.append(f"export interface {d.name} {{")
            if d.union:
                out.append(f"  {defs[d.union].discriminator}: {json.dumps(d.tag)};")
            out += fields(d.fields)
            out += ["}", ""]
        elif d.kind == "union":
            out += doc(d.doc)
            out.append(f"export type {d.name} =")
            for i, v in enumerate(d.variants):
                out.append(f"  | {v}{';' if i == len(d.variants) - 1 else ''}")
            tags = ", ".join(json.dumps(defs[v].tag) for v in d.variants)
            out += [f"export const {upper_snake(d.name)}_{upper_snake(plural(d.discriminator))} = [{tags}] as const;"]
            if any(defs[v].since for v in d.variants):
                out.append(f"export const {upper_snake(d.name)}_SINCE: Record<string, number> = {{ "
                           + ", ".join(f"{defs[v].tag}: {defs[v].since}" for v in d.variants) + " };")
            out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------------------------------------------------------------
# Swift: Codable structs that never fail on a missing or mistyped field (it takes its zero value, or nil), unions as enums whose unknown or
# unreadable variants decode as .unknown, enums as string constants (a newer hub's values pass through).

SWIFT_KEYWORDS = {"protocol", "extension", "default", "func", "class", "struct", "enum", "var", "let", "in", "is", "as",
                  "for", "if", "return", "switch", "case", "where", "import", "init", "operator", "static", "public",
                  "private", "internal", "repeat", "while", "do", "try", "throw", "nil", "true", "false", "super",
                  "self", "Self", "Any", "inout", "subscript", "typealias", "associatedtype", "deinit", "fileprivate",
                  "else", "guard", "defer", "break", "continue", "fallthrough", "throws", "rethrows"}


def swift_name(name: str) -> str:
    return name if name.startswith("Extension") else "Extension" + name


def swift_ident(s: str) -> str:
    return f"`{s}`" if s in SWIFT_KEYWORDS else s


def gen_swift(defs: dict[str, Def]) -> str:
    out = [f"// {HEADER}", "// The extension protocol's and views' types (schema/extension/).", "", "import Foundation", ""]

    def stype(t: TypeRef) -> str:
        k = t.kind
        if k in ("string", "time"):
            return "String"
        if k == "int":
            return "Int"
        if k == "int64":
            return "Int64"
        if k == "number":
            return "Double"
        if k == "bool":
            return "Bool"
        if k == "any":
            return "JSONValue"
        if k == "array":
            return f"[{stype(t.of)}]"
        if k == "map":
            return f"[String: {stype(t.of)}]"
        d = defs[t.ref]
        return "String" if d.kind == "enum" else swift_name(t.ref)

    def zero(t: TypeRef) -> str:
        k = t.kind
        if k in ("string", "time"):
            return '""'
        if k in ("int", "int64", "number"):
            return "0"
        if k == "bool":
            return "false"
        if k == "any":
            return ".null"
        if k == "array":
            return "[]"
        if k == "map":
            return "[:]"
        d = defs[t.ref]
        if d.kind == "enum":
            return '""'
        if d.kind == "union":
            raise SchemaError(f"a required field of union type {t.ref}: not in the subset")
        return f"{swift_name(t.ref)}()"

    def struct(d: Def) -> list[str]:
        name = swift_name(d.name)
        lines = comment("/// ", d.doc)
        lines.append(f"nonisolated struct {name}: Codable, Equatable, Sendable {{")
        for f in d.fields:
            lines += comment("    /// ", f.doc)
            typ = stype(f.type) + ("" if f.required else "?")
            lines.append(f"    var {swift_ident(lower_camel(f.name))}: {typ}")
        if d.fields:
            lines.append("")
            params = ", ".join(f"{swift_ident(lower_camel(f.name))}: {stype(f.type)}"
                               + (f" = {zero(f.type)}" if f.required else "? = nil") for f in d.fields)
            lines.append(f"    init({params}) {{")
            for f in d.fields:
                n = lower_camel(f.name)
                lines.append(f"        self.{n} = {swift_ident(n)}")
            lines += ["    }", "", "    enum CodingKeys: String, CodingKey {"]
            for f in d.fields:
                n = lower_camel(f.name)
                lines.append(f"        case {swift_ident(n)}" + (f' = "{f.name}"' if n != f.name else ""))
            lines += ["    }", "", "    init(from decoder: Decoder) throws {",
                      "        let c = try decoder.container(keyedBy: CodingKeys.self)"]
            for f in d.fields:
                n = lower_camel(f.name)
                key = swift_ident(n)
                if f.required:
                    lines.append(f"        self.{n} = (try? c.decodeIfPresent({stype(f.type)}.self, forKey: .{key})) "
                                 f"?? {zero(f.type)}")
                else:
                    lines.append(f"        self.{n} = try? c.decodeIfPresent({stype(f.type)}.self, forKey: .{key})")
            lines.append("    }")
        else:
            lines += ["    init() {}", "", "    init(from decoder: Decoder) throws {}", "",
                      "    func encode(to encoder: Encoder) throws {}"]
        lines += ["}", ""]
        return lines

    for d in defs.values():
        if d.kind == "enum":
            out += comment("/// ", d.doc or f"Values of {d.name}.")
            out.append(f"nonisolated enum {swift_name(d.name)} {{")
            for v in d.values:
                out.append(f'    static let {swift_ident(lower_camel(v))} = "{v}"')
            out.append(f"    static let all = [{', '.join(json.dumps(v) for v in d.values)}]")
            out += ["}", ""]
        elif d.kind == "any":
            out += comment("/// ", d.doc) + [f"typealias {swift_name(d.name)} = JSONValue", ""]
        elif d.kind == "struct":
            out += struct(d)
        elif d.kind == "union":
            name, disc = swift_name(d.name), d.discriminator
            out += comment("/// ", d.doc)
            out.append(f"nonisolated enum {name}: Codable, Equatable, Sendable {{")
            for v in d.variants:
                out.append(f"    case {swift_ident(lower_camel(defs[v].tag))}({swift_name(v)})")
            out += [f"    /// A {disc} this app does not know, or a variant it could not read: skipped when drawn.",
                    f"    case unknown({disc}: String)", "",
                    f"    static let {lower_camel(plural(disc))} = "
                    f"[{', '.join(json.dumps(defs[v].tag) for v in d.variants)}]", ""]
            if any(defs[v].since for v in d.variants):
                out += [f"    /// The UI version that brought each {disc}.",
                        "    static let since: [String: Int] = ["
                        + ", ".join(f"{json.dumps(defs[v].tag)}: {defs[v].since}" for v in d.variants) + "]", ""]
            out += ["    private enum TagKey: String, CodingKey {", f"        case tag = \"{disc}\"", "    }", "",
                    f"    var {swift_ident(disc)}: String {{", "        switch self {"]
            for v in d.variants:
                out.append(f"        case .{swift_ident(lower_camel(defs[v].tag))}: {json.dumps(defs[v].tag)}")
            out += [f"        case .unknown(let t): t", "        }", "    }", "",
                    "    init(from decoder: Decoder) throws {",
                    "        let t = (try? decoder.container(keyedBy: TagKey.self).decode(String.self, forKey: .tag)) "
                    "?? \"\"",
                    "        switch t {"]
            for v in d.variants:
                out.append(f"        case {json.dumps(defs[v].tag)}: self = (try? {swift_name(v)}(from: decoder))"
                           f".map {{ .{swift_ident(lower_camel(defs[v].tag))}($0) }} ?? .unknown({disc}: t)")
            out += [f"        default: self = .unknown({disc}: t)", "        }", "    }", "",
                    "    func encode(to encoder: Encoder) throws {", "        switch self {"]
            for v in d.variants:
                out.append(f"        case .{swift_ident(lower_camel(defs[v].tag))}(let v): try v.encode(to: encoder)")
            out += ["        case .unknown: break", "        }",
                    "        var c = encoder.container(keyedBy: TagKey.self)",
                    f"        try c.encode({swift_ident(disc)}, forKey: .tag)", "    }", "}", ""]
    return "\n".join(out)



"""Repository paths quoted in the current docs must exist.

Files move often (the Persona rename, scripts split by purpose, Persona Link moving under apple/); a doc that still points
at the old place sends the next reader, or Agent, looking for a file that is gone. This checks every `backticked` path that
starts with a top-level directory of the repository. Dated records under docs/archive/ and the redesign drafts keep the
paths of their own time and are not checked; neither are the rename docs, which name the retired paths on purpose.
"""
from pathlib import Path
import re
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[2]

# Top-level directories whose paths docs quote. Paths under scripts/ are often written relative to it (deploy/deploy.sh).
TOP = ("android", "apple", "deploy", "docs", "integrations", "scripts", "server", "site", "spec", "web", "prototypes")

SKIP_FILES = {
    "docs/rename.md",
    "docs/rename-acceptance.md",
    "docs/rename-pr-audit.md",
    "docs/lessons/rename.md",
}

# Generated by a build or a script, so a clean checkout does not have them.
GENERATED = {
    "apple/Config.xcconfig",
    "apple/Persona.xcodeproj",
    "android/app/build/outputs/apk/debug/app-debug.apk",
    "web/dist",
    "apple/Jarvis.xcodeproj",  # the kept compatibility symlink to the generated Persona.xcodeproj
}

# Only these exact screenshot outputs are generated, and their actual producers must declare the same default.
GENERATED_SCREENSHOTS = {
    "android/feature/settings/build/channel-shots":
        "android/feature/settings/src/test/kotlin/persona/feature/settings/ChannelsShotsTest.kt",
    "android/feature/chat/build/channel-shots":
        "android/feature/chat/src/test/kotlin/persona/feature/chat/ChannelSourceShotsTest.kt",
    "android/feature/settings/build/hub-update-shots":
        "android/feature/settings/src/test/kotlin/persona/feature/settings/HubUpdateShotsTest.kt",
    "android/feature/settings/build/translation-shots":
        "android/feature/settings/src/test/kotlin/persona/feature/settings/TranslationSettingsShotsTest.kt",
    "android/feature/inbox/build/translation-shots":
        "android/feature/inbox/src/test/kotlin/persona/feature/inbox/InboxTranslationShotsTest.kt",
}

# Quoted on purpose though not at the repository root: paths in another project or in the mock hub's fake file tree.
ELSEWHERE = {
    "docs/guide.pdf",  # mock_hub.py's fake browse tree (docs/android.md)
    "docs/icon.png",  # a file the mock hub does not have (docs/mac.md)
    "scripts/ol.sh",  # inside skills/lark-connector/ (docs/assistant.md)
    # The Go check's overlay maps this absent path to a test source in /tmp (spec/fixtures/sort/README.md).
    "server/internal/hub/spec_sort_fixture_test.go",
}

QUOTED = re.compile(r"`([^`\s]+)`")


def doc_files():
    files = [ROOT / name for name in ("CLAUDE.md", "README.md", "THIRD_PARTY_NOTICES.md", "scripts/README.md")]
    files += sorted((ROOT / "docs").glob("*.md")) + sorted((ROOT / "docs/lessons").glob("*.md"))
    files += [ROOT / "spec/README.md"] + sorted((ROOT / "spec/fixtures").glob("*/README.md"))
    return [f for f in files if f.exists() and f.relative_to(ROOT).as_posix() not in SKIP_FILES]


def quoted_paths(line):
    for token in QUOTED.findall(line):
        # The spec READMEs name a symbol after a full-width colon: `apple/Shared/Models.swift：Interaction`.
        path = re.split(r"[:：]", token.split("#", 1)[0], maxsplit=1)[0].rstrip(".,;/")
        if "/" not in path or path.split("/", 1)[0] not in TOP:
            continue
        # Placeholders, globs, prefixes of a family of files and elided paths are not literal paths.
        if any(mark in path for mark in ("<", ">", "*", "{", "$", "…", "...")) or path.endswith(("-", "_")):
            continue
        yield path


def generated_screenshot(path):
    producer = GENERATED_SCREENSHOTS.get(path)
    if producer is None:
        return False
    source = ROOT / producer
    if not source.is_file():
        return False
    output = "build/" + path.split("/build/", 1)[1]
    pattern = (r'(?m)^\s*private\s+fun\s+out\(\)(?:\s*:\s*File)?\s*=\s*'
               r'File\(\s*System\.getProperty\("persona\.shots"\)\s*\?:\s*"'
               + re.escape(output) + r'"\s*\)')
    return re.search(pattern, source.read_text()) is not None


def exists(path):
    if path in GENERATED_SCREENSHOTS:
        return generated_screenshot(path)
    return path in GENERATED or path in ELSEWHERE or (ROOT / path).exists() or (ROOT / "scripts" / path).exists()


class DocPathTests(unittest.TestCase):
    def test_generated_screenshots_have_matching_source_producers(self):
        for path in GENERATED_SCREENSHOTS:
            with self.subTest(path=path):
                self.assertTrue(generated_screenshot(path))
                self.assertTrue(exists(path))

    def test_missing_or_changed_producers_and_unknown_outputs_are_rejected(self):
        path, producer = next(iter(GENERATED_SCREENSHOTS.items()))
        output = "build/" + path.split("/build/", 1)[1]
        with tempfile.TemporaryDirectory(prefix="doc-shot-producer-") as directory:
            root = Path(directory)
            with patch(__name__ + ".ROOT", root):
                (root / path).mkdir(parents=True)
                self.assertFalse(exists(path))
                source = root / producer
                source.parent.mkdir(parents=True)
                source.write_text(f'// private fun out() = File(System.getProperty("persona.shots") ?: "{output}")\n'
                                  'private fun out() = File(System.getProperty("persona.shots") ?: "build/other-shots")\n')
                self.assertFalse(exists(path))
                source.write_text(f'private fun out() = File(System.getProperty("persona.shots") ?: "{output}")\n')
                self.assertTrue(exists(path))
                source.unlink()
                self.assertFalse(exists(path))
                self.assertFalse(exists(path + "-unknown"))
                self.assertFalse(exists("android/feature/missing/src/Unknown.kt"))

    def test_symbol_after_a_colon_is_not_part_of_the_path(self):
        self.assertEqual(["apple/Shared/Models.swift"], list(quoted_paths("`apple/Shared/Models.swift：Interaction`")))
        self.assertEqual(["server/internal/hub/hub.go"], list(quoted_paths("`server/internal/hub/hub.go:120`")))

    def test_spec_readmes_are_checked(self):
        checked = {doc.relative_to(ROOT).as_posix() for doc in doc_files()}
        self.assertIn("spec/README.md", checked)
        self.assertIn("spec/fixtures/wire/README.md", checked)

    def test_quoted_repository_paths_exist(self):
        missing = []
        for doc in doc_files():
            for number, line in enumerate(doc.read_text(errors="ignore").splitlines(), 1):
                if "github.com/" in line:  # a path inside another project, quoted with its source
                    continue
                missing += [f"{doc.relative_to(ROOT)}:{number}: {path}" for path in quoted_paths(line) if not exists(path)]
        self.assertEqual([], missing, "docs quote paths that are not in the repository; update them to where the file is now")


if __name__ == "__main__":
    unittest.main()
